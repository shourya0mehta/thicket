SNR_KEYS = [("+10", "+10 dB"), ("+0", "0 dB"), ("-10", "-10 dB")]


def ci(t) -> str:
    return ek.fmt_ci(t)


def pc(t) -> str:
    """Rate triple [p, lo, hi] as percent."""
    return f"{100 * t[0]:.0f}% ({100 * t[1]:.0f} to {100 * t[2]:.0f})"


def pts(t) -> str:
    """Difference triple in percentage points."""
    return f"{100 * t[0]:+.0f} points ({100 * t[1]:+.0f} to {100 * t[2]:+.0f})"


def summary(res: dict) -> list[str]:
    cl = res["clean"]
    d = cl["diff_v2_minus_v1"]
    E = res["mixtures_eval"]["backend"]
    ff = res["clean_bio_false_contamination_flag"]["backend"]
    out = [
        f"Decision: v2 {'meets' if res['decision']['ship'] else 'does not meet'} the ship criteria written down before the results (table below)"
        + (
            ", so it is exported and becomes the backend default."
            if res["decision"]["ship"] and "export" in res
            else ", so v1 stays the default."
            if not res["decision"]["ship"]
            else "."
        ),
        f"Clean ESC-50 test folds: macro AP v1 {ci(cl['v1_f1']['macro']['ap'])}, v2 {ci(cl['v2_f1']['macro']['ap'])}; difference {ci(d['macro_ap'])}. Macro F1 v1 {ci(cl['v1_f1']['macro']['f1'])}, v2 {ci(cl['v2_f1']['macro']['f1'])}; difference {ci(d['macro_f1'])}.",
        "Held-out mixtures (a bird, frog or insect clip plus one of six contaminants, backend warning rule): the added contaminant is flagged at "
        + ", ".join(
            f"{lab} by v1 in {pc(E['v1'][f'all@{k}']['detected'])} and v2 in {pc(E['v2'][f'all@{k}']['detected'])}"
            for k, lab in SNR_KEYS
        )
        + " of mixtures.",
        "Gain in detection (v2 minus v1, same mixtures): "
        + ", ".join(f"{lab} {pts(E['gain_v2_minus_v1'][f'all@{k}'])}" for k, lab in SNR_KEYS)
        + ".",
        f"False contamination warnings on clean bird, frog and insect test clips (backend rule): v1 {pc(ff['v1'])}, v2 {pc(ff['v2'])}; difference {pts(ff['diff'])}.",
        "The mixtures are synthetic: two curated ESC-50 clips added together. They are not field recordings, and these are not field accuracy numbers.",
    ]
    if "_v2a" in res:
        out.insert(
            1,
            "A first attempt (v2a, union labels, equal weights) flagged far more contaminants under calls but lost clean accuracy and failed the criteria; v2 (v2b) keeps mixture training only where it does not cost clean accuracy. v2b was designed after seeing v2a's results (see the honesty note).",
        )
    return out


def criteria_table(res: dict) -> list[str]:
    c = res["config"]["ship_criteria"]
    ch = res["decision"]["checks"]
    rows = [
        (
            "clean_macro_ap_diff_ci_low",
            f"Lower end of the 95% CI of clean macro AP difference (v2 minus v1) is at least {c['clean_macro_ap_diff_ci_low_min']}",
        ),
        (
            "clean_macro_ap_diff_point",
            f"Clean macro AP difference is at least {c['clean_macro_ap_diff_point_min']}",
        ),
        (
            "clean_macro_f1_diff_point",
            f"Clean macro F1 difference is at least {c['clean_macro_f1_diff_point_min']}",
        ),
        ("mixture_gain_0dB_ci_low", "Detection gain at 0 dB: lower end of 95% CI above 0"),
        ("mixture_gain_minus10dB_ci_low", "Detection gain at -10 dB: lower end of 95% CI above 0"),
        (
            "clean_bio_false_flag_increase",
            f"Increase in false contamination warnings on clean bird, frog and insect clips is at most {c['clean_bio_false_flag_increase_max_backend_rule']}",
        ),
    ]
    L = ["| Criterion | Value | Pass |", "|---|---|---|"]
    for key, text in rows:
        L.append(f"| {text} | {ch[key]['value']:+.3f} | {'yes' if ch[key]['pass'] else 'no'} |")
    return L


