def write_all(res: dict) -> None:
    if mx.RESULTS_V2A.exists():
        res = dict(res)
        res["_v2a"] = json.loads(mx.RESULTS_V2A.read_text())
    write_report(res)
    written = [REPORT]
    if "export" in res:
        write_card(res)
        written.append(CARD)
    for p in written:
        if chr(0x2014) in p.read_text():
            raise RuntimeError(f"em dash found in {p}")
    print("[v2 report] wrote " + ", ".join(str(p) for p in written))
